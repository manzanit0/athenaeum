import { expect, test } from "@playwright/test";
import { addBook, notice, shelfBook } from "./helpers";

test("files books under categories, browses by them and tidies them up", async ({ page, request }) => {
  await addBook(request, "lighthouse.epub");
  const faros = await addBook(request, "faros.epub");
  const knots = await addBook(request, "knots.pdf");
  const lighthouse = shelfBook(page, "The Lighthouse Keepers", "Mara Quill");
  const northern = shelfBook(page, "Faros del norte", "Mara Quill");
  const splices = shelfBook(page, "Knots and Splices", "Eli Tarn");

  await page.goto("/");
  await page.getByRole("button", { name: "Categorise books" }).click();
  await page.getByLabel("Select The Lighthouse Keepers").check();
  await page.getByLabel("Select Faros del norte").check();
  const selected = page.getByRole("region", { name: "Selected books" });
  await expect(selected).toContainText("2 books selected");
  await selected.getByLabel("Category", { exact: true }).fill("Voyages / Seafaring");
  await selected.getByRole("button", { name: "Add category" }).click();
  await expect(notice(page, "Filed 2 books under “Voyages / Seafaring”")).toBeVisible();
  await page.getByLabel("Select The Lighthouse Keepers").uncheck();
  await page.getByLabel("Select Faros del norte").uncheck();
  await page.getByLabel("Select Knots and Splices").check();
  await selected.getByLabel("Category", { exact: true }).fill("Voyages / Ropework");
  await selected.getByRole("button", { name: "Add category" }).click();
  await expect(notice(page, "Filed 1 book under “Voyages / Ropework”")).toBeVisible();
  await selected.getByRole("button", { name: "Done" }).click();

  const narrow = page.getByRole("complementary", { name: "Narrow the shelf" });
  const categories = narrow.getByRole("group", { name: "Categories" });
  await expect(categories.getByRole("checkbox", { name: "Any category" })).toBeChecked();
  await expect(categories.getByRole("checkbox", { name: /^Seafaring/ })).toHaveCount(0);
  await categories.getByRole("checkbox", { name: "Voyages 3" }).check();
  await expect(page).toHaveURL(/tag=Voyages$/);
  await expect(lighthouse).toBeVisible();
  await expect(splices).toBeVisible();
  await expect(page.getByText(/^3 of \d+ books$/)).toBeVisible();
  await expect(categories.getByRole("checkbox", { name: "Seafaring 2" })).toBeVisible();
  await categories.getByRole("checkbox", { name: "Voyages 3" }).uncheck();
  await expect(categories.getByRole("checkbox", { name: "Seafaring 2" })).toBeVisible();
  await categories.getByRole("button", { name: "Hide the categories under Voyages" }).click();
  await expect(categories.getByRole("checkbox", { name: "Seafaring 2" })).toHaveCount(0);
  await categories.getByRole("button", { name: "Show the categories under Voyages" }).click();
  await categories.getByRole("checkbox", { name: "Seafaring 2" }).check();
  await expect(lighthouse).toBeVisible();
  await expect(northern).toBeVisible();
  await expect(splices).toHaveCount(0);
  await expect(page.getByText(/^2 of \d+ books$/)).toBeVisible();
  await expect(categories.getByRole("checkbox", { name: "Any category" })).not.toBeChecked();
  await categories.getByRole("checkbox", { name: "Ropework 1" }).check();
  await expect(splices).toBeVisible();
  await expect(page.getByText(/^3 of \d+ books$/)).toBeVisible();
  await categories.getByRole("checkbox", { name: "Ropework 1" }).uncheck();
  await expect(splices).toHaveCount(0);

  const voyages = categories.getByRole("checkbox", { name: "Voyages 3" });
  await expect(voyages).toHaveJSProperty("indeterminate", true);
  await voyages.check();
  await expect(categories.getByRole("checkbox", { name: "Seafaring 2" })).not.toBeChecked();
  await expect(splices).toBeVisible();
  await expect(page).toHaveURL(/tag=Voyages$/);
  await categories.getByRole("checkbox", { name: "Seafaring 2" }).check();
  await expect(voyages).not.toBeChecked();
  await expect(voyages).toHaveJSProperty("indeterminate", true);
  await expect(splices).toHaveCount(0);
  await expect(page).toHaveURL(/tag=Voyages\+%2F\+Seafaring$/);
  await page.goto("/?tag=Voyages");
  await expect(categories.getByRole("checkbox", { name: "Seafaring 2" })).toBeVisible();
  await page.goto("/?tag=Voyages&tag=Voyages+%2F+Seafaring");
  await expect(lighthouse).toBeVisible();
  await expect(splices).toHaveCount(0);
  await expect(voyages).not.toBeChecked();

  const languages = narrow.getByRole("group", { name: "Language" });
  await languages.getByRole("checkbox", { name: /^Spanish/ }).check();
  await expect(northern).toBeVisible();
  await expect(lighthouse).toHaveCount(0);
  await expect(categories.getByRole("checkbox", { name: "Seafaring 1" })).toBeChecked();
  await expect(categories.getByRole("checkbox", { name: "Ropework 0" })).toBeDisabled();
  await page.reload();
  await expect(northern).toBeVisible();
  await expect(lighthouse).toHaveCount(0);
  await expect(categories.getByRole("checkbox", { name: "Seafaring 1" })).toBeChecked();
  await page.getByRole("button", { name: "Stop narrowing to Spanish" }).click();
  await expect(lighthouse).toBeVisible();
  await expect(languages.getByRole("checkbox", { name: "Any language" })).toBeChecked();

  await categories.getByRole("checkbox", { name: "Any category" }).check();
  await expect(splices).toBeVisible();
  await expect(page).toHaveURL("/");
  await categories.getByRole("checkbox", { name: "Seafaring 2" }).check();

  await northern.click();
  await expect(page).toHaveURL(`/books/${faros.id}`);
  await expect(page.getByRole("link", { name: "Books in Voyages / Seafaring" })).toBeVisible();
  await page.getByRole("link", { name: "Back to the library" }).click();
  await expect(page).toHaveURL(/tag=Voyages\+%2F\+Seafaring/);
  await expect(splices).toHaveCount(0);

  await page.goto(`/books/${knots.id}`);
  const filed = page.getByRole("group", { name: "Categories" });
  await expect(filed.getByRole("listitem")).toContainText(["Voyages / Ropework"]);
  await filed.getByLabel("Add a category").selectOption("Voyages");
  await expect(filed.getByRole("listitem")).toContainText(["Voyages"]);
  await filed.getByLabel("Add a category").selectOption("Voyages / Ropework");
  await filed.getByLabel("Add a category").selectOption("Voyages / Seafaring");
  await expect(filed.getByRole("listitem")).toContainText(["Voyages / Ropework", "Voyages / Seafaring"]);
  await page.getByRole("button", { name: "Save changes" }).click();
  await expect(notice(page, "Changes saved")).toBeVisible();
  await page.getByRole("link", { name: "Books in Voyages / Seafaring" }).click();
  await expect(splices).toBeVisible();
  await expect(page.getByText(/^3 of \d+ books$/)).toBeVisible();

  await narrow.getByRole("link", { name: "Manage categories" }).click();
  await expect(page.getByRole("heading", { level: 1, name: "Categories" })).toBeVisible();
  const list = page.getByRole("main");
  await list.getByRole("button", { name: "Rename Voyages / Ropework" }).click();
  await list.getByLabel("New name for Voyages / Ropework").fill("voyages/seafaring");
  await list.getByRole("button", { name: "Save name" }).click();
  await expect(notice(page, "Merged “Voyages / Ropework” into “voyages / seafaring” on 1 book")).toBeVisible();
  await expect(list.getByRole("link", { name: "Ropework" })).toHaveCount(0);
  await list.getByRole("button", { name: "Rename Voyages", exact: true }).click();
  await list.getByLabel("New name for Voyages", { exact: true }).fill("Sea");
  await list.getByRole("button", { name: "Save name" }).click();
  await expect(notice(page, "Renamed “Voyages” to “Sea” on 3 books")).toBeVisible();
  await list.getByRole("link", { name: "Seafaring" }).click();
  await expect(page).toHaveURL(/tag=Sea\+%2F\+/);
  await expect(lighthouse).toBeVisible();
  await expect(splices).toBeVisible();

  await page.goto("/categories");
  await list.getByRole("button", { name: /^Remove Sea \/ / }).click();
  await page.getByRole("dialog").getByRole("button", { name: "Remove category" }).click();
  await expect(notice(page, /Took 3 books out of “Sea \/ /)).toBeVisible();
  await expect(list.getByRole("link", { name: "Sea", exact: true })).toHaveCount(0);

  await page.goto(`/books/${knots.id}`);
  await page.getByRole("link", { name: "Books by Eli Tarn" }).click();
  await expect(page).toHaveURL(/author=Eli\+Tarn/);
  await expect(splices).toBeVisible();
  await expect(lighthouse).toHaveCount(0);
});
